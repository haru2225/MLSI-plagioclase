#!/usr/bin/env python3
"""Write the LAMMPS pair_style table files for the BKS and SHIK potentials.

BKS  (van Beest, Kramer, van Santen, PRL 64, 1955 (1990)) for pure SiO2, with the 30-6 Lennard-Jones
     core of Saika-Voivod, Sciortino, Poole, PRE 69, 041503 (2004), Table I, which removes the
     unphysical collapse ("fusion") of BKS at high T/P.  Short-range part shifted to zero at 10 A;
     Coulomb is handled by coul/long + pppm (see potentials/BKS.mod).
SHIK (Sundararaman, Huang, Ispas, Kob, J. Chem. Phys. 150, 154505 (2019), Tables 1-2; silica part from
     J. Chem. Phys. 148, 194504 (2018)) for Na/Ca/Al-bearing systems.  Buckingham + D/r^24, multiplied by
     G(r) = exp(-gamma^2/(r-rc)^2), gamma = 0.2 A, rc = 8 A; Coulomb is the Wolf form of the paper,
     identical to coul/dsf with alpha = 0 and a 10 A cutoff (see potentials/SHIK.mod).
     Pairs that are absent from Table 2 (Si-Al, Na-Al, Ca-Al, Na-Ca) only interact via Coulomb.

Usage:  python tools/make_tables.py            (writes potentials/BKS_SiO2.table, potentials/SHIK.table)
"""
from pathlib import Path

import numpy as np

EV = 1.602176634e-19
OUT = Path(__file__).resolve().parents[1] / "potentials"

# BKS: A (eV), B (1/A), C (eV A^6); 30-6 core: eps (eV), sigma (A).  The core parameters are converted
# from the SI values of Saika-Voivod et al. (2004), Table I.
BKS = {
    "SiO": dict(A=18003.7572, B=4.87318, C=133.5381, eps=4.963460e-22 / EV, sig=1.313635),
    "OO": dict(A=1388.7730, B=2.76000, C=175.0000, eps=1.6839685e-22 / EV, sig=1.779239),
}
BKS_RC, BKS_RLO, BKS_N = 10.0, 0.6, 9401

# SHIK, Table 2 of the 2019 paper: A (eV), B (1/A), C (eV A^6), D (eV A^24)
SHIK = {
    "O-O": (1120.5, 2.8927, 26.132, 16800),
    "O-Si": (23108, 5.0979, 139.70, 66),
    "Si-Si": (2798.0, 4.4073, 0.0, 3423204),
    "O-Na": (1127566, 6.8986, 40.562, 16800),
    "Si-Na": (495653, 5.4151, 0.0, 16800),
    "Na-Na": (1476.9, 3.4075, 0.0, 16800),
    "O-Ca": (101376, 5.2914, 68.684, 16800),
    "Si-Ca": (544421, 5.3256, 0.0, 16800),
    "Ca-Ca": (12384, 5.4829, 0.0, 16800),
    "O-Al": (21740, 5.3054, 65.815, 66),
    "Al-Al": (1799.1, 3.6778, 100.0, 16800),
}
SHIK_RC, SHIK_GAMMA, SHIK_RLO, SHIK_N = 8.0, 0.2, 0.6, 7401


def bks(r, A, B, C, eps, sig):
    e = A * np.exp(-B * r) - C / r**6 + 4 * eps * ((sig / r) ** 30 - (sig / r) ** 6)
    f = A * B * np.exp(-B * r) - 6 * C / r**7 + 4 * eps * (30 * sig**30 / r**31 - 6 * sig**6 / r**7)
    return e, f


def shik(r, A, B, C, D):
    e = A * np.exp(-B * r) - C / r**6 + D / r**24
    f = A * B * np.exp(-B * r) - 6 * C / r**7 + 24 * D / r**25
    g = np.zeros_like(r)
    dg = np.zeros_like(r)
    m = r < SHIK_RC
    x = r[m] - SHIK_RC
    g[m] = np.exp(-SHIK_GAMMA**2 / x**2)
    dg[m] = g[m] * 2 * SHIK_GAMMA**2 / x**3
    # V = e*g  ->  F = -dV/dr = f*g - e*dg
    return e * g, f * g - e * dg


def write(fname, header, sections):
    with open(fname, "w") as fh:
        fh.write(header)
        for key, r, e, f in sections:
            fh.write(f"\n{key}\nN {len(r)} R {r[0]:.6f} {r[-1]:.6f}\n\n")
            for i, (ri, ei, fi) in enumerate(zip(r, e, f), 1):
                fh.write(f"{i} {ri:.6f} {ei:.10e} {fi:.10e}\n")


def main():
    OUT.mkdir(exist_ok=True)
    r = np.linspace(BKS_RLO, BKS_RC, BKS_N)
    sec = []
    for key, p in BKS.items():
        e, f = bks(r, **p)
        e_rc, _ = bks(np.array([BKS_RC]), **p)
        sec.append((key, r, e - e_rc[0], f))
    write(OUT / "BKS_SiO2.table",
          "# BKS short-range part (Buckingham + Saika-Voivod 30-6 core), shifted to 0 at 10 A. Units: A, eV, eV/A\n"
          "# Generated by tools/make_tables.py\n", sec)

    r = np.linspace(SHIK_RLO, SHIK_RC, SHIK_N)
    sec = [(key, r, *shik(r, *p)) for key, p in SHIK.items()]
    write(OUT / "SHIK.table",
          "# SHIK short-range part, Buckingham + D/r^24, smoothed by exp(-0.2^2/(r-8)^2). Units: A, eV, eV/A\n"
          "# Generated by tools/make_tables.py\n", sec)
    print("wrote", OUT / "BKS_SiO2.table", "and", OUT / "SHIK.table")


if __name__ == "__main__":
    main()
